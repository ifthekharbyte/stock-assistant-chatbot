"""
eval/evaluate.py

Agent evaluation, following 04-evaluation/lessons/14-agent-evaluation.md
as closely as our domain allows:

- Run the agent on each ground-truth question (eval/ground_truth.py),
  and save the answer + tool-call trajectory -- our version of the
  course's `agent-answers.csv`.
- Judge two things with a structured-output LLM judge, exactly the
  course's two-dimensional AgentEvaluation:
    - answer_score: is the final answer good, given the tool data it's
      built from?
    - trajectory_score: were the tool calls reasonable for the question?
- Run both steps in parallel with ThreadPoolExecutor + map_progress,
  same as the course.

One domain difference: the course's FAQ agent has a fixed ground-truth
*answer* (A->Q->A'), because questions are generated from existing FAQ
answers. Ours doesn't -- questions are generated from a (tool, ticker)
pair, not a fixed answer (live market data has no static "correct"
value) -- so answer_score judges "did the answer use real, specific
tool data to address the question" rather than "does it match a
reference answer". We additionally compute a tool-selection hit rate
(did the agent call the expected tool at all), which the course doesn't
need since retrieval hit rate already covers that role for its FAQ
search tool.

Run with: python eval/evaluate.py
Requires eval/ground_truth.csv (run eval/ground_truth.py first).
"""

import csv
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Literal

import pandas as pd
from pydantic import BaseModel, Field

sys.path.append(str(Path(__file__).resolve().parent.parent))

from agent import agent_loop  # noqa: E402
from evaluation_utils import calc_total_price, get_client, llm_structured_retry, map_progress  # noqa: E402

client = get_client()

GROUND_TRUTH_PATH = Path(__file__).resolve().parent / "ground_truth.csv"
ANSWERS_PATH = Path(__file__).resolve().parent / "agent_answers.csv"
EVAL_PATH = Path(__file__).resolve().parent / "agent_evaluations.csv"


# ----------------------------------------------------------------------
# Step 1: run the agent on every ground-truth question
# ----------------------------------------------------------------------

def generate_agent_answer(rec: dict) -> dict:
    record, _messages = agent_loop(rec["question"])
    return {
        "question": rec["question"],
        "expected_tool": rec["tool"],
        "answer_agent": record.answer,
        "tool_calls": json.dumps(record.tool_calls),
        "cost": record.cost,
    }


# ----------------------------------------------------------------------
# Step 2: judge the answer and the tool-call trajectory
# ----------------------------------------------------------------------

class AgentEvaluation(BaseModel):
    answer_reasoning: str = Field(description="Reasoning about whether the final answer is correct.")
    answer_score: Literal["good", "bad"] = Field(
        description="'good' if the answer uses specific, real tool data to address the question."
    )
    trajectory_reasoning: str = Field(description="Reasoning about whether the tool calls were useful.")
    trajectory_score: Literal["good", "bad"] = Field(
        description="'good' if the tool calls were reasonable for the question."
    )


agent_judge_instructions = """
You are an expert evaluator for a stock market assistant. You will be given:
1. A question from a retail investor
2. An answer generated by an AI agent
3. The tool calls the agent made before answering

Evaluate two things:

Answer quality:
- Does the answer directly address the question?
- Does it cite specific figures (prices, percentages, dates, article
  titles, etc.) rather than vague or generic statements?
- It should not invent numbers not backed by a tool call.

Trajectory quality:
- Was at least one tool called before answering (for anything requiring
  live data)?
- Were the tool(s) called relevant to the question (e.g. the right
  ticker, the right kind of data)?
- Did the agent avoid duplicate or unnecessary tool calls?
- Was the number of tool calls reasonable? Usually 1-2 is enough for a
  single-ticker question; more calls are fine for multi-ticker
  comparisons but should have a clear reason.

Mark answer_score as 'good' if the final answer is correct and specific.
Mark trajectory_score as 'good' if the tool calls were reasonable.
""".strip()

agent_judge_prompt = """
Question:
{question}

Agent Answer:
{answer_agent}

Tool Calls:
{tool_calls}
""".strip()


def evaluate_agent_answer(rec: dict):
    tool_calls = json.loads(rec["tool_calls"])
    prompt = agent_judge_prompt.format(
        question=rec["question"],
        answer_agent=rec["answer_agent"],
        tool_calls=json.dumps(tool_calls, indent=2),
    )
    return llm_structured_retry(client, agent_judge_instructions, prompt, AgentEvaluation)


def judge_agent_record(rec: dict):
    evaluation, usage = evaluate_agent_answer(rec)
    expected_tool = rec["expected_tool"]
    called_tools = {c["name"] for c in json.loads(rec["tool_calls"])}
    result = {
        "question": rec["question"],
        "expected_tool": expected_tool,
        "tool_hit": expected_tool in called_tools,
        "answer_score": evaluation.answer_score,
        "answer_reasoning": evaluation.answer_reasoning,
        "trajectory_score": evaluation.trajectory_score,
        "trajectory_reasoning": evaluation.trajectory_reasoning,
    }
    return result, usage


def main():
    if not GROUND_TRUTH_PATH.exists():
        raise SystemExit("Run eval/ground_truth.py first to create eval/ground_truth.csv")

    with GROUND_TRUTH_PATH.open() as f:
        ground_truth = list(csv.DictReader(f))

    # max_workers=1: Groq's free-tier TPM cap is a shared budget across all
    # concurrent requests, not per-request -- two agent loops running at once
    # can jointly exceed it even when neither is oversized alone (confirmed:
    # a 413 "request too large" at max_workers=2 with no single call above
    # ~6k tokens). responses_create_retry() still absorbs transient 429s.
    print(f"Running the agent on {len(ground_truth)} ground-truth questions...")
    with ThreadPoolExecutor(max_workers=1) as pool:
        agent_answers = map_progress(pool, ground_truth, generate_agent_answer)

    df_agent = pd.DataFrame(agent_answers)
    df_agent.to_csv(ANSWERS_PATH, index=False)
    print(f"Agent cost: ${df_agent['cost'].sum():.5f}")
    print(f"Wrote {ANSWERS_PATH}")

    print("\nJudging answers + trajectories...")
    with ThreadPoolExecutor(max_workers=1) as pool:
        judged = map_progress(pool, agent_answers, judge_agent_record)

    results = [r for r, _usage in judged]
    usages = [u for _r, u in judged]

    df_eval = pd.DataFrame(results)
    df_eval.to_csv(EVAL_PATH, index=False)
    print(f"Judge cost: ${calc_total_price(usages):.5f}")
    print(f"Wrote {EVAL_PATH}")

    n = len(df_eval)
    print("\n=== Summary ===")
    print(f"Tool-selection hit rate: {df_eval['tool_hit'].mean():.0%} ({df_eval['tool_hit'].sum()}/{n})")
    print("\nAnswer score:")
    print(df_eval["answer_score"].value_counts(normalize=True).to_string())
    print("\nTrajectory score:")
    print(df_eval["trajectory_score"].value_counts(normalize=True).to_string())


if __name__ == "__main__":
    main()
